import assert from 'node:assert/strict';
import {nativeHTTPPortObservation,assertNativeHTTPPortsFree} from '../../../integration/turn/native-http-ports.mjs';
import net from 'node:net';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {readFileSync} from 'node:fs';
if(process.platform!=='linux')throw Error('Controlled probe requires owned Linux namespace; not skipped');
const rows=()=>readFileSync('/proc/net/tcp','utf8').trim().split('\n').slice(1).map(line=>line.trim().split(/\s+/));
const server=net.createServer(socket=>socket.resume());server.listen(64451,'127.0.0.1');await once(server,'listening');
const child=spawn('/bin/bash',['-c','exec 3<>/dev/tcp/127.0.0.1/64451; printf ready; read -r release; exec 3>&-; exec 3<&-'],{stdio:['pipe','pipe','pipe']});
await once(child.stdout,'data');
const active=rows().find(row=>parseInt(row[2].split(':')[1],16)===64451&&row[3]==='01');
if(!active)throw Error('owned client not found');
const port=parseInt(active[1].split(':')[1],16);
const closed=once(child,'close');child.stdin.end('\n');await closed;
await new Promise(ok=>server.close(ok));
const states=rows().filter(row=>parseInt(row[1].split(':')[1],16)===port).map(row=>row[3]);
const observation=nativeHTTPPortObservation(port);
const socket=net.createServer();
const bind=await new Promise(ok=>{socket.once('error',e=>ok(e.code));socket.listen(port,'127.0.0.1',()=>socket.close(()=>ok('PASS')));});
assert.equal(child.exitCode,0);assert.equal(bind,'EADDRINUSE');assert.ok(observation.tcpStates.TIME_WAIT>0);assert.equal(observation.tcpStates.LISTEN??0,0);
await assert.rejects(()=>assertNativeHTTPPortsFree({ports:[port]}),/TIME_WAIT/);
console.log(JSON.stringify({observation,experiment:'owned Linux client exit/close and listener close',ephemeralRange:readFileSync('/proc/sys/net/ipv4/ip_local_port_range','utf8').trim(),port,clientExited:child.exitCode===0,states,bind,listenerRows:rows().filter(row=>parseInt(row[1].split(':')[1],16)===port&&row[3]==='0A').length}));

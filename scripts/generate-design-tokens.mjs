import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const manifestPath = resolve("brand/tokens/visepanda.tokens.json");
const outputPath = resolve("app/design-tokens.generated.css");
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));

const variables = [
  ...Object.entries(manifest.color).map(([name, token]) => [`--vp-${name.slice(3).toLowerCase()}`, token.value]),
  ["--vp-font-display", manifest.typography.display.family],
  ["--vp-font-body", manifest.typography.body.family],
  ["--vp-font-multilingual", manifest.typography.multilingual.family],
  ["--vp-space", manifest.layout["space-base"].value],
  ["--vp-radius", manifest.layout["radius-standard"].value],
  ["--vp-feature-radius", manifest.layout["radius-feature"].value],
  ["--vp-touch-minimum", manifest.layout["touch-minimum"].value],
  ["--vp-focus-outline", manifest.material.outline.value],
  ["--vp-sticker-edge", manifest.material["sticker-edge"].value],
  ["--vp-shadow", manifest.material.shadow.value],
];

const content = [
  "/* Generated by scripts/generate-design-tokens.mjs from brand/tokens/visepanda.tokens.json. Do not edit. */",
  ":root {",
  ...variables.map(([name, value]) => `  ${name}: ${value};`),
  "}",
  "",
].join("\n");

const temporaryOutputPath = `${outputPath}.tmp`;
writeFileSync(temporaryOutputPath, content);
renameSync(temporaryOutputPath, outputPath);
